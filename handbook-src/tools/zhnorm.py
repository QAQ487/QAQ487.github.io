SAFE_KEEP=['關係','聯係']  # protect
def norm(s):
    if not s: return s
    prot={}
    for i,k in enumerate(SAFE_KEEP):
        tok=f'\x00{i}\x00'; s=s.replace(k,tok); prot[tok]=k
    # protect html tags/attrs and URLs from replacement
    parts=re.split(r'(<[^>]+>|https?://\S+)',s)
    out=[]
    for p in parts:
        if p.startswith('<') or p.startswith('http'): out.append(p); continue
        for _ in range(2):
            for a,b in PAIRS: p=p.replace(a,b)
        p=re.sub(r'(?<![相近類疑酷看好])似(?![乎的])','像',p)
        p=re.sub(r'邊(?=[個度項處])','哪',p)
        p=re.sub(r'(?<![可通步])行路','走路',p)
        p=re.sub(r'(?<![希期眺盼渴願失聲威觀指展仰守張探絕欲慾冀名])望(?![遠])','看',p)
        p=re.sub(r'(?<![相不共如等認混協贊雷])同(?![時一樣步類義框屏名拍條種理意伴事級款位向個色期軸心等屬質場區比化胞學])','與',p)
        out.append(p)
    s=''.join(out)
    for t,k in prot.items(): s=s.replace(t,k)
    return s
